import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from './frontmatter.mjs';

const ROOT = process.cwd();
const CONTENT_DIR = path.join(ROOT, 'content', 'deep-dives', 'cards');
const LIB_DIR = path.join(ROOT, 'src', 'lib');

const OUTPUT_META = path.join(LIB_DIR, 'deep-dive-cards-meta.ts');
const OUTPUT_LOOKUP = path.join(LIB_DIR, 'deep-dive-cards-lookup.ts');
const OUTPUT_LOADERS = path.join(LIB_DIR, 'deep-dive-cards-loaders.ts');

function getSlugFromFilename(filename) {
  return filename.replace(/\.mdx?$/i, '');
}

function inferTitleFromContent(content) {
  const lines = content.split('\n');
  for (const line of lines) {
    const match = line.match(/^#\s+(.+)\s*$/);
    if (match) return match[1].trim();
  }
  return 'Card Deep Dive';
}

function inferDescriptionFromContent(content) {
  const lines = content.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (trimmed.startsWith('#')) continue;
    if (trimmed.startsWith('<')) continue;
    return trimmed.replace(/\s+/g, ' ').slice(0, 180);
  }
  return 'Supplementary notes.';
}

function formatTsString(value) {
  return JSON.stringify(value ?? '');
}

function fileHeader() {
  return [
    '/*',
    ' * AUTO-GENERATED FILE - DO NOT EDIT',
    ' *',
    ' * Generated by: scripts/generate-deep-dive-cards-manifest.mjs',
    ' */',
    '',
  ];
}

async function main() {
  const entries = fsSync.existsSync(CONTENT_DIR) ? await fs.readdir(CONTENT_DIR) : [];
  const mdxFiles = entries
    .filter((file) => file.endsWith('.mdx') || file.endsWith('.md'))
    .sort((a, b) => a.localeCompare(b));

  const manifest = [];

  for (const file of mdxFiles) {
    const filePath = path.join(CONTENT_DIR, file);
    const raw = await fs.readFile(filePath, 'utf8');
    const parsed = parseFrontmatter(raw);

    const slug = getSlugFromFilename(file);
    const title =
      typeof parsed.data.title === 'string' && parsed.data.title.trim().length > 0
        ? parsed.data.title.trim()
        : inferTitleFromContent(parsed.content);

    const description =
      typeof parsed.data.description === 'string' && parsed.data.description.trim().length > 0
        ? parsed.data.description.trim()
        : inferDescriptionFromContent(parsed.content);

    const cardStableId =
      typeof parsed.data.cardStableId === 'string' && parsed.data.cardStableId.trim().length > 0
        ? parsed.data.cardStableId.trim()
        : undefined;

    const questionId =
      typeof parsed.data.questionId === 'string' && parsed.data.questionId.trim().length > 0
        ? parsed.data.questionId.trim()
        : undefined;

    const rotation =
      typeof parsed.data.rotation === 'string' && parsed.data.rotation.trim().length > 0
        ? parsed.data.rotation.trim()
        : undefined;

    const week =
      typeof parsed.data.week === 'number' && Number.isFinite(parsed.data.week)
        ? parsed.data.week
        : typeof parsed.data.week === 'string' && parsed.data.week.trim()
          ? Number.parseInt(parsed.data.week.trim(), 10)
          : undefined;

    const tags =
      Array.isArray(parsed.data.tags) && parsed.data.tags.every((t) => typeof t === 'string')
        ? parsed.data.tags.map((t) => t.trim()).filter(Boolean)
        : undefined;

    manifest.push({
      slug,
      file,
      title,
      description,
      cardStableId,
      questionId,
      rotation,
      week: Number.isFinite(week) ? week : undefined,
      tags,
    });
  }

  // --- File 1: Meta (slug → full metadata) ---
  const metaLines = fileHeader();
  metaLines.push('export interface DeepDiveCardMeta {');
  metaLines.push('  slug: string;');
  metaLines.push('  file: string;');
  metaLines.push('  title: string;');
  metaLines.push('  description: string;');
  metaLines.push('  cardStableId?: string;');
  metaLines.push('  questionId?: string;');
  metaLines.push('  rotation?: string;');
  metaLines.push('  week?: number;');
  metaLines.push('  tags?: string[];');
  metaLines.push('}');
  metaLines.push('');

  metaLines.push('export const deepDiveCardMetaBySlug: Record<string, DeepDiveCardMeta> = {');
  for (const entry of manifest) {
    metaLines.push(`  ${formatTsString(entry.slug)}: {`);
    metaLines.push(`    slug: ${formatTsString(entry.slug)},`);
    metaLines.push(`    file: ${formatTsString(entry.file)},`);
    metaLines.push(`    title: ${formatTsString(entry.title)},`);
    metaLines.push(`    description: ${formatTsString(entry.description)},`);
    if (entry.cardStableId) metaLines.push(`    cardStableId: ${formatTsString(entry.cardStableId)},`);
    if (entry.questionId) metaLines.push(`    questionId: ${formatTsString(entry.questionId)},`);
    if (entry.rotation) metaLines.push(`    rotation: ${formatTsString(entry.rotation)},`);
    if (Number.isFinite(entry.week)) metaLines.push(`    week: ${entry.week},`);
    if (entry.tags && entry.tags.length > 0) metaLines.push(`    tags: ${JSON.stringify(entry.tags)},`);
    metaLines.push('  },');
  }
  metaLines.push('};');
  metaLines.push('');
  metaLines.push('export const allDeepDiveCardSlugs = Object.keys(deepDiveCardMetaBySlug);');
  metaLines.push('');

  // --- File 2: Lookup (questionId → lightweight card info) ---
  const lookupLines = fileHeader();
  lookupLines.push('export interface DeepDiveCardLookup {');
  lookupLines.push('  slug: string;');
  lookupLines.push('  title: string;');
  lookupLines.push('  description: string;');
  lookupLines.push('}');
  lookupLines.push('');
  lookupLines.push('export const deepDiveCardByQuestionId: Record<string, DeepDiveCardLookup> = {');
  for (const entry of manifest) {
    if (!entry.questionId) continue;
    lookupLines.push(`  ${formatTsString(entry.questionId)}: {`);
    lookupLines.push(`    slug: ${formatTsString(entry.slug)},`);
    lookupLines.push(`    title: ${formatTsString(entry.title)},`);
    lookupLines.push(`    description: ${formatTsString(entry.description)},`);
    lookupLines.push('  },');
  }
  lookupLines.push('};');
  lookupLines.push('');

  // --- File 3: Loaders (slug → dynamic import) ---
  const loaderLines = fileHeader();
  loaderLines.push("import type { ComponentType } from 'react';");
  loaderLines.push('');
  loaderLines.push('export const deepDiveCardLoaderBySlug: Record<string, () => Promise<{ default: ComponentType }>> = {');
  for (const entry of manifest) {
    loaderLines.push(
      `  ${formatTsString(entry.slug)}: () => import('@/../content/deep-dives/cards/${entry.file}'),`
    );
  }
  loaderLines.push('};');
  loaderLines.push('');

  await fs.mkdir(LIB_DIR, { recursive: true });
  await Promise.all([
    fs.writeFile(OUTPUT_META, metaLines.join('\n'), 'utf8'),
    fs.writeFile(OUTPUT_LOOKUP, lookupLines.join('\n'), 'utf8'),
    fs.writeFile(OUTPUT_LOADERS, loaderLines.join('\n'), 'utf8'),
  ]);

  console.log(`Generated ${manifest.length} card entries across 3 files:`);
  console.log(`  ${OUTPUT_META}`);
  console.log(`  ${OUTPUT_LOOKUP}`);
  console.log(`  ${OUTPUT_LOADERS}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
