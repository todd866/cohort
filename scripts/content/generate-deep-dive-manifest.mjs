import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from './frontmatter.mjs';

const ROOT = process.cwd();
const CONTENT_DIR = path.join(ROOT, 'content', 'deep-dives');
const OUTPUT_FILE = path.join(ROOT, 'src', 'lib', 'deep-dives.ts');

function getSlugFromFilename(filename) {
  return filename.replace(/\.mdx?$/i, '');
}

function inferTitleFromContent(content) {
  const lines = content.split('\n');
  for (const line of lines) {
    const match = line.match(/^#\s+(.+)\s*$/);
    if (match) return match[1].trim();
  }
  return 'Deep Dive';
}

function inferDescriptionFromContent(content) {
  const lines = content.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (trimmed.startsWith('#')) continue;
    if (trimmed.startsWith('<')) continue;
    return trimmed.replace(/\s+/g, ' ').slice(0, 180);
  }
  return 'Supplementary notes.';
}

function formatTsString(value) {
  return JSON.stringify(value ?? '');
}

async function main() {
  const entries = fsSync.existsSync(CONTENT_DIR) ? await fs.readdir(CONTENT_DIR) : [];
  const mdxFiles = entries
    .filter((file) => file.endsWith('.mdx') || file.endsWith('.md'))
    .sort((a, b) => a.localeCompare(b));

  const manifest = [];

  for (const file of mdxFiles) {
    const filePath = path.join(CONTENT_DIR, file);
    const raw = await fs.readFile(filePath, 'utf8');
    const parsed = parseFrontmatter(raw);

    const slug = getSlugFromFilename(file);
    const title =
      typeof parsed.data.title === 'string' && parsed.data.title.trim().length > 0
        ? parsed.data.title.trim()
        : inferTitleFromContent(parsed.content);

    const description =
      typeof parsed.data.description === 'string' && parsed.data.description.trim().length > 0
        ? parsed.data.description.trim()
        : inferDescriptionFromContent(parsed.content);

    const duration =
      typeof parsed.data.duration === 'string' && parsed.data.duration.trim().length > 0
        ? parsed.data.duration.trim()
        : undefined;

    const backLink =
      typeof parsed.data.backLink === 'string' && parsed.data.backLink.trim().length > 0
        ? parsed.data.backLink.trim()
        : undefined;

    const rotation =
      typeof parsed.data.rotation === 'string' && parsed.data.rotation.trim().length > 0
        ? parsed.data.rotation.trim()
        : undefined;

    const week =
      typeof parsed.data.week === 'number' && Number.isFinite(parsed.data.week)
        ? parsed.data.week
        : typeof parsed.data.week === 'string' && parsed.data.week.trim()
          ? Number.parseInt(parsed.data.week.trim(), 10)
          : undefined;

    const tags =
      Array.isArray(parsed.data.tags) && parsed.data.tags.every((t) => typeof t === 'string')
        ? parsed.data.tags.map((t) => t.trim()).filter(Boolean)
        : undefined;

    const hasVideo =
      typeof parsed.data.hasVideo === 'boolean'
        ? parsed.data.hasVideo
        : /<Video\b/i.test(raw);

    manifest.push({
      slug,
      file,
      title,
      description,
      duration,
      backLink,
      rotation,
      week: Number.isFinite(week) ? week : undefined,
      tags,
      hasVideo,
    });
  }

  const lines = [];
  lines.push('/*');
  lines.push(' * AUTO-GENERATED FILE - DO NOT EDIT');
  lines.push(' *');
  lines.push(' * Generated by: scripts/generate-deep-dive-manifest.mjs');
  lines.push(' */');
  lines.push('');
  lines.push("import type { ComponentType } from 'react';");
  lines.push('');
  lines.push('export interface DeepDiveMeta {');
  lines.push('  slug: string;');
  lines.push('  file: string;');
  lines.push('  title: string;');
  lines.push('  description: string;');
  lines.push('  duration?: string;');
  lines.push('  backLink?: string;');
  lines.push('  rotation?: string;');
  lines.push('  week?: number;');
  lines.push('  tags?: string[];');
  lines.push('  hasVideo?: boolean;');
  lines.push('}');
  lines.push('');

  lines.push('export const deepDiveMetaBySlug: Record<string, DeepDiveMeta> = {');
  for (const entry of manifest) {
    lines.push(`  ${formatTsString(entry.slug)}: {`);
    lines.push(`    slug: ${formatTsString(entry.slug)},`);
    lines.push(`    file: ${formatTsString(entry.file)},`);
    lines.push(`    title: ${formatTsString(entry.title)},`);
    lines.push(`    description: ${formatTsString(entry.description)},`);
    if (entry.duration) lines.push(`    duration: ${formatTsString(entry.duration)},`);
    if (entry.backLink) lines.push(`    backLink: ${formatTsString(entry.backLink)},`);
    if (entry.rotation) lines.push(`    rotation: ${formatTsString(entry.rotation)},`);
    if (Number.isFinite(entry.week)) lines.push(`    week: ${entry.week},`);
    if (entry.tags && entry.tags.length > 0) lines.push(`    tags: ${JSON.stringify(entry.tags)},`);
    if (typeof entry.hasVideo === 'boolean') lines.push(`    hasVideo: ${entry.hasVideo},`);
    lines.push('  },');
  }
  lines.push('};');
  lines.push('');

  lines.push('export const deepDiveLoaderBySlug: Record<string, () => Promise<{ default: ComponentType }>> = {');
  for (const entry of manifest) {
    lines.push(
      `  ${formatTsString(entry.slug)}: () => import('@/../content/deep-dives/${entry.file}'),`
    );
  }
  lines.push('};');
  lines.push('');

  lines.push('export const allDeepDiveSlugs = Object.keys(deepDiveMetaBySlug);');
  lines.push('');

  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, lines.join('\n'), 'utf8');
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
